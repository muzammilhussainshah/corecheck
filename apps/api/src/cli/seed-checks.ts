import type { EntityManager } from 'typeorm';
import { dateInTimeZone } from '../common/clock.js';

const question = (id: string, text: string, overrides: object = {}) => ({
  id,
  text,
  type: 'pass_fail',
  mandatory: true,
  failAnswer: null,
  min: null,
  max: null,
  meterTypeId: null,
  requireComment: 'on_fail',
  requirePhoto: 'never',
  options: [],
  failOptions: [],
  offlineOnFail: false,
  defectSeverity: null,
  showIf: null,
  ...overrides,
});

/**
 * Milestone 3 demo data for an organisation with plant but no check
 * templates yet: a daily pre-use template with defect and offline triggers,
 * a follow-up and a single selection; a technical lifting inspection with
 * approval; a Defect verification template; schedules on two plant; and one
 * completed check whose failed answer raised a Defect.
 *
 * The schedules' first checks are generated by the API's schedule run
 * shortly after it starts.
 */
export const seedChecks = async (
  manager: EntityManager,
  orgId: string,
): Promise<void> => {
  const [{ existing }] = (await manager.query(
    `select count(*)::int as existing from corecheck.check_templates
      where org_id = $1 and purpose <> 'reception'`,
    [orgId],
  )) as [{ existing: number }];
  if (existing > 0) return;
  const one = async (sql: string, params: unknown[]): Promise<string> =>
    ((await manager.query(sql, params)) as Array<{ id: string }>)[0]!.id;
  const find = async (sql: string, params: unknown[]) =>
    ((await manager.query(sql, params)) as Array<{ id: string }>)[0]?.id;

  const [{ adminId, timeZone }] = (await manager.query(
    `select u.id as "adminId", o.time_zone as "timeZone"
       from corecheck.users u
       join corecheck.organisations o on o.id = u.org_id
       join corecheck.roles r on r.id = u.role_id
      where u.org_id = $1 and r.standard_key = 'admin' limit 1`,
    [orgId],
  )) as [{ adminId: string; timeZone: string }];
  const user = (lastName: string) =>
    find('select id from corecheck.users where org_id = $1 and last_name = $2', [
      orgId,
      lastName,
    ]);
  const operative = (await user('Operative')) ?? adminId;
  const supervisor = (await user('Supervisor')) ?? adminId;
  const lifting = await find(
    `select id from corecheck.teams where org_id = $1 and name = 'Lifting'`,
    [orgId],
  );
  const hours = await find(
    `select id from corecheck.meter_types where org_id = $1 and name = 'Hours'`,
    [orgId],
  );
  const crane = await find(
    `select id from corecheck.plant_types where org_id = $1 and name = 'Mobile crane'`,
    [orgId],
  );
  const excavator = await find(
    `select id from corecheck.plants where org_id = $1 and asset_id = 'PLT-000001'`,
    [orgId],
  );
  const liveCrane = await find(
    `select id from corecheck.plants where org_id = $1 and asset_id = 'PLT-000002'`,
    [orgId],
  );
  if (!excavator || !liveCrane) return;

  const template = async (
    purpose: string,
    name: string,
    approvalMode: 'automatic' | 'manual',
    questions: object[],
    extra: {
      eligibility?: object;
      recurrence?: object;
      requireCorrectiveAction?: boolean;
    } = {},
  ) => {
    const templateId = await one(
      `insert into corecheck.check_templates (org_id, purpose, name, created_by)
       values ($1, $2, $3, $4) returning id`,
      [orgId, purpose, name, adminId],
    );
    const versionId = await one(
      `insert into corecheck.check_template_versions
         (org_id, template_id, version, state, approval_mode, questions,
          eligibility, recurrence, require_corrective_action,
          published_at, published_by, created_by)
       values ($1, $2, 1, 'published', $3, $4::jsonb, $5::jsonb, $6::jsonb, $7,
               now(), $8, $8)
       returning id`,
      [
        orgId,
        templateId,
        approvalMode,
        JSON.stringify(questions),
        JSON.stringify(extra.eligibility ?? {}),
        extra.recurrence ? JSON.stringify(extra.recurrence) : null,
        extra.requireCorrectiveAction ?? false,
        adminId,
      ],
    );
    return { templateId, versionId };
  };

  const daily = await template(
    'operational',
    'Daily pre-use check',
    'automatic',
    [
      question('tyres', 'Tyres and tracks in good condition', {
        defectSeverity: 'minor',
      }),
      question('hydraulics', 'Hydraulic hoses free of leaks', {
        defectSeverity: 'major',
        offlineOnFail: true,
        requirePhoto: 'on_fail',
      }),
      question('leak', 'Where is the leak?', {
        type: 'text',
        requireComment: 'never',
        showIf: { questionId: 'hydraulics', when: 'fail', values: [] },
      }),
      question('fuel', 'Fuel level', {
        type: 'single_select',
        options: ['Full', 'Three quarters', 'Half', 'Low'],
        failOptions: ['Low'],
        requireComment: 'never',
      }),
      ...(hours
        ? [
            question('hours', 'Hour meter reading', {
              type: 'meter',
              meterTypeId: hours,
              requireComment: 'never',
            }),
          ]
        : []),
    ],
    {
      recurrence: { frequency: 'daily', customUnit: null, customCount: null },
    },
  );
  await template(
    'technical',
    'Weekly lifting inspection',
    'manual',
    [
      question('hook', 'Hook and safety latch serviceable', {
        defectSeverity: 'critical',
        offlineOnFail: true,
      }),
      question('rope', 'Wire rope free of kinks and broken wires', {
        defectSeverity: 'major',
        offlineOnFail: true,
      }),
      question('limits', 'Overload and limit switches tested', {
        type: 'yes_no',
        failAnswer: 'no',
      }),
    ],
    {
      eligibility: crane ? { plantTypeIds: [crane] } : {},
      recurrence: { frequency: 'weekly', customUnit: null, customCount: null },
    },
  );
  await template(
    'defect_verification',
    'Defect repair verification',
    'manual',
    [
      question('repaired', 'Repair completed and holds under test'),
      question('safe', 'Plant safe to return to use', {
        type: 'yes_no',
        failAnswer: 'no',
      }),
    ],
    { requireCorrectiveAction: true },
  );

  const today = dateInTimeZone(new Date(), timeZone);
  const schedule = (
    name: string,
    templateId: string,
    plantId: string,
    frequency: string,
    assignee: { user?: string; team?: string },
    requiresApproval: boolean,
  ) =>
    manager.query(
      `insert into corecheck.check_schedules
         (org_id, name, template_id, plant_id, frequency, start_on, next_due_on,
          requires_approval, assignee_user_id, assignee_team_id, created_by)
       values ($1, $2, $3, $4, $5, $6, $6, $7, $8, $9, $10)`,
      [
        orgId,
        name,
        templateId,
        plantId,
        frequency,
        today,
        requiresApproval,
        assignee.user ?? null,
        assignee.team ?? null,
        adminId,
      ],
    );
  await schedule(
    'EX-101 daily pre-use',
    daily.templateId,
    excavator,
    'daily',
    lifting ? { team: lifting } : { user: operative },
    false,
  );
  const lift = await find(
    `select id from corecheck.check_templates where org_id = $1 and name = 'Weekly lifting inspection'`,
    [orgId],
  );
  if (lift)
    await schedule('MC-2 weekly lifting', lift, liveCrane, 'weekly', { user: supervisor }, true);

  // One completed check whose tyres failed: it raised a minor Defect.
  const checkId = await one(
    `insert into corecheck.checks
       (org_id, plant_id, template_version_id, source, status, assignee_user_id,
        available_on, due_on, requires_review, created_by, started_at, started_by,
        submitted_at, submitted_by, completed_at, outcome_reasons)
     values ($1, $2, $3, 'manual', 'completed', $4, $5, $5, false, $6,
             now() - interval '1 hour', $4, now() - interval '50 minutes', $4,
             now() - interval '50 minutes', '["Failed: Tyres and tracks in good condition"]')
     returning id`,
    [orgId, excavator, daily.versionId, operative, today, supervisor],
  );
  const answers = [
    ['tyres', 'fail', 'Front left track tension low'],
    ['hydraulics', 'pass', null],
    ['fuel', 'Half', null],
  ] as const;
  for (const [questionId, value, comment] of answers) {
    await manager.query(
      `insert into corecheck.check_answers
         (org_id, check_id, question_id, value, comment, answered_by, answered_at)
       values ($1, $2, $3, $4::jsonb, $5, $6, now() - interval '55 minutes')`,
      [orgId, checkId, questionId, JSON.stringify(value), comment, operative],
    );
    await manager.query(
      `insert into corecheck.check_answer_changes
         (org_id, check_id, question_id, value, comment, changed_by, changed_at)
       values ($1, $2, $3, $4::jsonb, $5, $6, now() - interval '55 minutes')`,
      [orgId, checkId, questionId, JSON.stringify(value), comment, operative],
    );
  }
  await manager.query(
    `insert into corecheck.check_submissions
       (org_id, check_id, submitted_by, submitted_at, answers, outcome, outcome_reasons)
     values ($1, $2, $3, now() - interval '50 minutes', $4::jsonb, 'completed',
             '["Failed: Tyres and tracks in good condition"]')`,
    [
      orgId,
      checkId,
      operative,
      JSON.stringify(
        answers.map(([questionId, value, comment]) => ({
          questionId,
          value,
          comment,
          answeredBy: operative,
          answeredAt: new Date().toISOString(),
          evidence: [],
        })),
      ),
    ],
  );
  await manager.query(
    `insert into corecheck.defects
       (org_id, plant_id, check_id, question_id, question_text, answer,
        answer_comment, raised_by, severity)
     values ($1, $2, $3, 'tyres', 'Tyres and tracks in good condition',
             '"fail"'::jsonb, 'Front left track tension low', $4, 'minor')`,
    [orgId, excavator, checkId, operative],
  );
};
