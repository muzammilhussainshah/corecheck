'use client';

import {
  Badge,
  Button,
  Card,
  Center,
  Group,
  Loader,
  Modal,
  MultiSelect,
  Select,
  SimpleGrid,
  Stack,
  Text,
  TextInput,
  Title,
} from '@mantine/core';
import { useForm } from '@mantine/form';
import {
  IconKey,
  IconLockOpen,
  IconUserCheck,
  IconUserOff,
} from '@tabler/icons-react';
import { useParams } from 'next/navigation';
import { useState } from 'react';
import type {
  ApiError,
  IssuedCredentials,
  UserDetail,
  UserWithCredentials,
} from '@corecheck/shared';
import {
  confirmAction,
  CredentialsCard,
  DetailList,
  ErrorAlert,
  formatDateTime,
  showApiErrors,
  UserStatusBadge,
} from '@corecheck/ui';
import { AppPageHeader } from '../../../../../components/AppPageHeader';
import {
  useUpdateUserMutation,
  useUserActionMutation,
  useUserQuery,
} from '../../../../../lib/api';
import { useRoleOptions, useScopeOptions } from '../../../../../lib/options';
import { useSession } from '../../../../../lib/session';

const ids = (items: { id: string }[]) => items.map((item) => item.id);

function DetailsCard({ user }: { user: UserDetail }) {
  const [update, { isLoading }] = useUpdateUserMutation();
  const form = useForm({
    initialValues: {
      firstName: user.firstName,
      lastName: user.lastName,
      email: user.email ?? '',
    },
  });
  const editable = user.capabilities.canEdit;

  const submit = form.onSubmit(async (values) => {
    const result = await update({
      id: user.id,
      ...values,
      email: values.email || null,
    });
    if (result.error) return showApiErrors(form, result.error as ApiError);
    form.resetDirty();
  });

  return (
    <Card withBorder>
      <Title order={4} mb="md">
        Details
      </Title>
      <form onSubmit={submit} noValidate>
        <Stack>
          <SimpleGrid cols={{ base: 1, sm: 2 }}>
            <TextInput
              label="First name"
              disabled={!editable}
              {...form.getInputProps('firstName')}
            />
            <TextInput
              label="Last name"
              disabled={!editable}
              {...form.getInputProps('lastName')}
            />
          </SimpleGrid>
          <TextInput
            label="Email"
            type="email"
            disabled={!editable}
            {...form.getInputProps('email')}
          />
          <TextInput
            label="Username"
            value={user.username}
            readOnly
            variant="filled"
            description="Generated by CoreCheck; it does not change."
          />
          {editable && (
            <Group justify="flex-end">
              <Button
                type="submit"
                loading={isLoading}
                disabled={!form.isDirty()}
              >
                Save details
              </Button>
            </Group>
          )}
        </Stack>
      </form>
    </Card>
  );
}

function AccessCard({ user }: { user: UserDetail }) {
  const [update, { isLoading }] = useUpdateUserMutation();
  const initial = {
    roleId: user.role.id,
    siteIds: ids(user.sites),
    teamIds: ids(user.teams),
    disciplineIds: ids(user.disciplines),
  };
  const form = useForm({ initialValues: initial });
  const roles = useRoleOptions(user.role.id);
  const scope = useScopeOptions(initial);
  const { canChangeRole, canAssignScope } = user.capabilities;

  const submit = form.onSubmit(async (values) => {
    const changes: Record<string, unknown> = {};
    if (canChangeRole && values.roleId !== user.role.id)
      changes.roleId = values.roleId;
    if (canAssignScope)
      Object.assign(changes, {
        siteIds: values.siteIds,
        teamIds: values.teamIds,
        disciplineIds: values.disciplineIds,
      });
    const result = await update({ id: user.id, ...changes });
    if (result.error) return showApiErrors(form, result.error as ApiError);
    form.resetDirty(values);
  });

  return (
    <Card withBorder>
      {/* Same heading spacing as Details, so both cards' fields line up. */}
      <Title order={4} mb="md">
        Role and access
      </Title>
      <form onSubmit={submit} noValidate>
        <Stack>
          <Select
            label="Role"
            data={roles}
            disabled={!canChangeRole}
            allowDeselect={false}
            {...form.getInputProps('roleId')}
          />
          <MultiSelect
            label="Sites"
            data={scope.sites}
            disabled={!canAssignScope}
            searchable
            {...form.getInputProps('siteIds')}
          />
          <MultiSelect
            label="Teams"
            data={scope.teams}
            disabled={!canAssignScope}
            searchable
            {...form.getInputProps('teamIds')}
          />
          <MultiSelect
            label="Disciplines"
            data={scope.disciplines}
            disabled={!canAssignScope}
            searchable
            {...form.getInputProps('disciplineIds')}
          />
          <Text size="xs" c="dimmed" mt={-6}>
            A user needs both a permission and the record in their sites, teams
            or disciplines.
          </Text>
          {(canChangeRole || canAssignScope) && (
            <Group justify="flex-end">
              <Button
                type="submit"
                loading={isLoading}
                disabled={!form.isDirty()}
              >
                Save role and access
              </Button>
            </Group>
          )}
        </Stack>
      </form>
    </Card>
  );
}

export default function UserPage() {
  const { id } = useParams<{ id: string }>();
  const { me } = useSession();
  const { data: user, error, isLoading } = useUserQuery(id);
  const [runAction] = useUserActionMutation();
  const [credentials, setCredentials] = useState<IssuedCredentials | null>(
    null,
  );
  const tz = me?.organisation.timeZone;

  if (isLoading) {
    return (
      <Center py="xl">
        <Loader />
      </Center>
    );
  }
  if (error || !user)
    return (
      <ErrorAlert
        error={error as ApiError}
        title="This user could not be shown"
      />
    );

  const name = `${user.firstName} ${user.lastName}`;
  const act =
    (action: 'deactivate' | 'reactivate' | 'reset-pin' | 'unlock') =>
    async () => {
      const result = await runAction({ id: user.id, action });
      if (result.error) return;
      if (action === 'reset-pin')
        setCredentials((result.data as UserWithCredentials).credentials);
    };
  const caps = user.capabilities;

  return (
    <>
      <AppPageHeader
        crumbs={[{ label: 'Users', href: '/admin/users' }, { label: name }]}
        title={
          <Group gap="sm">
            {name}
            <UserStatusBadge status={user.status} />
          </Group>
        }
        description={`${user.role.name} · ${user.username}`}
        actions={
          <>
            {caps.canResetPin && (
              <Button
                variant="default"
                leftSection={<IconKey size={16} />}
                onClick={() =>
                  confirmAction({
                    title: 'Reset PIN?',
                    message: `${name} will get a new temporary PIN and be signed out. Their account is unlocked if it was locked.`,
                    confirmLabel: 'Reset PIN',
                    onConfirm: act('reset-pin'),
                  })
                }
              >
                Reset PIN
              </Button>
            )}
            {caps.canUnlock && (
              <Button
                variant="default"
                leftSection={<IconLockOpen size={16} />}
                onClick={act('unlock')}
              >
                Unlock
              </Button>
            )}
            {caps.canReactivate && (
              <Button
                variant="default"
                leftSection={<IconUserCheck size={16} />}
                onClick={act('reactivate')}
              >
                Reactivate
              </Button>
            )}
            {caps.canDeactivate && (
              <Button
                color="red"
                variant="light"
                leftSection={<IconUserOff size={16} />}
                onClick={() =>
                  confirmAction({
                    title: 'Deactivate user?',
                    message: `${name} will be signed out and unable to sign in. Their history is kept and their seat is freed.`,
                    confirmLabel: 'Deactivate',
                    danger: true,
                    onConfirm: act('deactivate'),
                  })
                }
              >
                Deactivate
              </Button>
            )}
          </>
        }
      />

      {/* Keyed on the saved values so the forms start afresh after a change. */}
      <SimpleGrid
        cols={{ base: 1, lg: 2 }}
        key={[
          user.role.id,
          user.status,
          user.email,
          ...ids(user.sites),
          ...ids(user.teams),
          ...ids(user.disciplines),
        ].join('|')}
      >
        <Stack>
          <DetailsCard user={user} />
          <Card withBorder>
            <Title order={4} mb="md">
              Account
            </Title>
            <DetailList
              items={[
                {
                  label: 'Last sign-in',
                  value: formatDateTime(user.lastLoginAt, tz),
                },
                { label: 'Created', value: formatDateTime(user.createdAt, tz) },
                {
                  label: 'PIN',
                  value: user.mustChangePin ? (
                    <Badge color="yellow" variant="light">
                      Temporary PIN not yet replaced
                    </Badge>
                  ) : (
                    'Set by the user'
                  ),
                },
                {
                  label: 'Recent failed attempts',
                  value: user.failedPinAttempts,
                },
                ...(user.lockedAt
                  ? [
                      {
                        label: 'Locked',
                        value: formatDateTime(user.lockedAt, tz),
                      },
                    ]
                  : []),
              ]}
            />
          </Card>
        </Stack>
        <AccessCard user={user} />
      </SimpleGrid>

      <Modal
        opened={!!credentials}
        onClose={() => setCredentials(null)}
        title="New temporary PIN"
        size="lg"
      >
        {credentials && (
          <CredentialsCard
            credentials={credentials}
            personName={name}
            timeZone={tz}
          />
        )}
      </Modal>
    </>
  );
}
